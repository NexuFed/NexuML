"""Generate or check the CUDA 12.8 / Python 3.13 / Linux AMD64 dependency lock."""

import argparse
import hashlib
import json
import os
from pathlib import Path
import subprocess
import tempfile
import tomllib


ROOT = Path(__file__).resolve().parents[1]
UV_VERSION = "0.13.5"
INPUT = Path("containers/cuda128.in")
LOCK = Path("containers/cuda128.txt")
FINGERPRINT_PREFIX = "# dependency-input-sha256: "


def fingerprint(root: Path) -> str:
    """Hash dependency metadata, not release versions or descriptive metadata.

    Returns:
        The SHA-256 digest of the version-independent dependency inputs.
    """
    manifests = []
    for relative in ("pyproject.toml", "library/pyproject.toml"):
        manifest = tomllib.loads((root / relative).read_text())
        project = manifest["project"]
        manifests.append(
            {
                key: project.get(key)
                for key in ("name", "requires-python", "dependencies", "optional-dependencies")
            }
            | {"uv": manifest.get("tool", {}).get("uv", {})}
        )
    inputs = {"manifests": manifests, "container": (root / INPUT).read_text()}
    return hashlib.sha256(json.dumps(inputs, sort_keys=True).encode()).hexdigest()


def check(root: Path) -> None:
    """Reject missing or stale locks without invoking uv or accessing the network.

    Raises:
        ValueError: If the lock is missing or dependency inputs changed.
    """
    expected = FINGERPRINT_PREFIX + fingerprint(root)
    if not (root / LOCK).is_file() or expected not in (root / LOCK).read_text().splitlines():
        raise ValueError("CUDA lock is stale; run python scripts/container_lock.py")


def generate(root: Path) -> None:
    """Compile all external dependencies with the pinned uv, without installing packages.

    Raises:
        ValueError: If the installed uv version differs from the Docker generator version.
    """
    input_fingerprint = fingerprint(root)
    version = subprocess.check_output(["uv", "--version"], text=True).split()[1]
    if version != UV_VERSION:
        raise ValueError(f"CUDA lock generation requires uv {UV_VERSION}, found {version}")
    # Ignore host backend/index overrides and never touch its active virtual environment.
    env = {
        key: value
        for key, value in os.environ.items()
        if not key.startswith(("UV_", "PIP_")) and key != "VIRTUAL_ENV"
    }
    scratch = Path("/tmp/opencode")
    scratch.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="nexuml-cuda128-", dir=scratch) as temporary:
        output = Path(temporary) / "requirements.txt"
        if (root / LOCK).exists():
            output.write_text((root / LOCK).read_text())
        env.update(TMPDIR=temporary, UV_CACHE_DIR=str(Path(temporary) / "cache"))
        subprocess.run(
            [
                "uv",
                "pip",
                "compile",
                "pyproject.toml",
                "library/pyproject.toml",
                str(INPUT),
                "--all-extras",
                "--no-emit-package",
                "nexuml",
                "--no-emit-package",
                "nexuml-library",
                "--torch-backend",
                "cu128",
                "--python-version",
                "3.13",
                "--python-platform",
                "x86_64-manylinux_2_39",
                "--only-binary=:all:",
                "--generate-hashes",
                "--emit-index-url",
                "--emit-index-annotation",
                "--emit-build-options",
                "--no-header",
                "--no-annotate",
                "--output-file",
                str(output),
                "--quiet",
            ],
            cwd=root,
            env=env,
            check=True,
        )
        if fingerprint(root) != input_fingerprint:
            raise ValueError("Dependency inputs changed during CUDA lock generation; retry")
        header = (
            f"# Generated by uv {UV_VERSION}; regenerate: python scripts/container_lock.py\n"
            "# CUDA 12.8.1 / Python 3.13 / Linux AMD64 (manylinux_2_39); all workspace extras.\n"
            f"{FINGERPRINT_PREFIX}{input_fingerprint}\n"
        )
        (root / LOCK).write_text(header + output.read_text())


def main() -> None:
    """Regenerate by default, or check dependency inputs without resolving anything."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check the input fingerprint only")
    args = parser.parse_args()
    try:
        (check if args.check else generate)(ROOT)
    except (ValueError, OSError, subprocess.CalledProcessError) as error:
        parser.exit(1, f"{error}\n")


if __name__ == "__main__":
    main()

"""Train one prepared NEX-233 FM ablation without accessing the test partition."""

from __future__ import annotations

import argparse
from pathlib import Path

import lightning as L

from nexuml.training.lightning import NexuSession
from nexuml_library.scenarios.flow.mimii_acoustic_ablation import mimii_acoustic_ablation


def train_ablation(
    prepared_file: str | Path,
    *,
    checkpoint_root: str | Path,
    width: int = 128,
    lr: float = 3e-4,
    max_epochs: int = 300,
    batch_size: int = 16,
    seed: int = 42,
    accelerator: str = "auto",
) -> None:
    """Execute fit and validation only, never NexuSession.run or test.

    Args:
        prepared_file: Immutable feature dataset generated by ablation_prepare.
        checkpoint_root: Destination root for unique experiment checkpoints.
        width: Width of two hidden vector-field layers.
        lr: Training learning rate.
        max_epochs: Training budget.
        batch_size: Training batch size.
        seed: Both training RNG and preparation pairing seed.
        accelerator: Lightning accelerator, e.g. cpu or gpu.

    Raises:
        ValueError: If width or training configuration is invalid.
        FileExistsError: If checkpoints already exist for this run identity.
    """
    if width <= 0:
        raise ValueError("MLP width must be positive")
    spec = mimii_acoustic_ablation(
        prepared_file,
        checkpoint_root=checkpoint_root,
        hidden_dims=[width, width],
        lr=lr,
        max_epochs=max_epochs,
        batch_size=batch_size,
        seed=seed,
    )
    run_name = f"{Path(prepared_file).stem}-mlp-{width}x{width}"
    checkpoint_dir = Path(checkpoint_root) / run_name
    if list(checkpoint_dir.glob("*.ckpt")):
        raise FileExistsError(
            f"Existing checkpoint(s) in {checkpoint_dir}; "
            "use a different run root instead of mixing training runs."
        )
    L.seed_everything(seed, workers=True)
    session = NexuSession.from_scenario(spec, accelerator=accelerator, devices=1)
    session.setup().fit()
    session.validate()
    print(f"Training finished. Checkpoints: {checkpoint_dir}")
    print("Held-out test was not evaluated.")


def main() -> None:
    """Run a single validation-only Flow Matching experiment."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--prepared-file", type=Path, required=True)
    parser.add_argument(
        "--checkpoint-root",
        type=Path,
        default=Path(".experiments/checkpoints/nex233-ablation"),
    )
    parser.add_argument("--width", type=int, choices=(128, 512), default=128)
    parser.add_argument("--lr", type=float, default=3e-4)
    parser.add_argument("--max-epochs", type=int, default=300)
    parser.add_argument("--batch-size", type=int, default=16)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--accelerator", choices=("auto", "cpu", "gpu"), default="auto")
    args = parser.parse_args()
    train_ablation(
        args.prepared_file,
        checkpoint_root=args.checkpoint_root,
        width=args.width,
        lr=args.lr,
        max_epochs=args.max_epochs,
        batch_size=args.batch_size,
        seed=args.seed,
        accelerator=args.accelerator,
    )


if __name__ == "__main__":
    main()
